import AppKit
import ApplicationServices
import CoreGraphics
import Foundation

// MARK: - Errors & Menu Support

nonisolated public enum ClickyAppDriverError: LocalizedError, Sendable {
    case userTookOver
    case accessibilityPermissionRequired
    case unsupportedKey(String)
    case eventCreationFailed(String)

    public var errorDescription: String? {
        switch self {
        case .userTookOver:
            return "The user took the screen back partway through, so this step may not be finished."
        case .accessibilityPermissionRequired:
            return "Accessibility permission is required to drive apps on screen."
        case .unsupportedKey(let key):
            return "Unknown key: \(key). Nothing was pressed."
        case .eventCreationFailed(let detail):
            return "Could not synthesize input event: \(detail)"
        }
    }
}

nonisolated public enum ClickyMouseButton: String, Sendable {
    case left
    case right
    case center
}

nonisolated public enum ClickyMenuStep: Sendable {
    case title(String)
    case shortcut(key: String, modifiers: CGEventFlags)
}

// MARK: - App Driver

@MainActor
public final class ClickyAppDriver {
    /// Magic userData tag placed on every synthetic CGEvent generated by Clicky
    /// so user-input monitors ignore Clicky's own cursor moves and keystrokes.
    nonisolated public static let syntheticEventUserDataTag: Int64 = 0x434C_4B59 // "CLKY"

    public private(set) var lastPoint: CGPoint?
    public var userTookOver: Bool = false

    private let eventSource: CGEventSource?
    private let shouldAbortCheck: @Sendable () -> Bool

    public init(shouldAbortCheck: @escaping @Sendable () -> Bool = { false }) {
        self.eventSource = CGEventSource(stateID: .hidSystemState)
        self.shouldAbortCheck = shouldAbortCheck
    }

    public func resetTakeOverState() {
        userTookOver = false
    }

    public func markUserTookOver() {
        userTookOver = true
    }

    public func currentCursorPosition() -> CGPoint {
        if let cgEvent = CGEvent(source: nil) {
            return cgEvent.location
        }
        let appKitPoint = NSEvent.mouseLocation
        return convertAppKitPointToCoreGraphics(appKitPoint)
    }

    // MARK: - Coordinate Conversion

    /// Converts AppKit bottom-left global screen coordinates to CoreGraphics top-left global coordinates.
    public func convertAppKitPointToCoreGraphics(_ appKitPoint: CGPoint) -> CGPoint {
        let primaryScreenHeight = NSScreen.screens.first?.frame.height
            ?? CGDisplayBounds(CGMainDisplayID()).height
        return CGPoint(x: appKitPoint.x, y: primaryScreenHeight - appKitPoint.y)
    }

    /// Converts CoreGraphics top-left global coordinates to AppKit bottom-left global coordinates.
    public func convertCoreGraphicsPointToAppKit(_ cgPoint: CGPoint) -> CGPoint {
        let primaryScreenHeight = NSScreen.screens.first?.frame.height
            ?? CGDisplayBounds(CGMainDisplayID()).height
        return CGPoint(x: cgPoint.x, y: primaryScreenHeight - cgPoint.y)
    }

    // MARK: - Mouse Actuation (CoreGraphics Top-Left Coordinates)

    public func moveMouse(to targetPoint: CGPoint, smoothSteps: Int = 12) async throws {
        try ensureCanActuate()

        let startPoint = lastPoint ?? currentCursorPosition()
        let steps = max(1, smoothSteps)

        for stepIndex in 1...steps {
            try ensureCanActuate()
            let progress = CGFloat(stepIndex) / CGFloat(steps)
            let eased = progress * progress * (3.0 - 2.0 * progress)
            let intermediate = CGPoint(
                x: startPoint.x + (targetPoint.x - startPoint.x) * eased,
                y: startPoint.y + (targetPoint.y - startPoint.y) * eased
            )
            try postMouseEvent(type: .mouseMoved, point: intermediate, button: .left, clickState: 0)
            lastPoint = intermediate
            if steps > 1 {
                try? await Task.sleep(nanoseconds: 10_000_000)
            }
        }
        lastPoint = targetPoint
    }

    public func click(
        at point: CGPoint,
        button: ClickyMouseButton = .left,
        clickCount: Int = 1
    ) async throws {
        try await moveMouse(to: point, smoothSteps: 8)
        try ensureCanActuate()

        let count = max(1, clickCount)
        let downType: CGEventType
        let upType: CGEventType
        let cgButton: CGMouseButton

        switch button {
        case .left:
            downType = .leftMouseDown
            upType = .leftMouseUp
            cgButton = .left
        case .right:
            downType = .rightMouseDown
            upType = .rightMouseUp
            cgButton = .right
        case .center:
            downType = .otherMouseDown
            upType = .otherMouseUp
            cgButton = .center
        }

        for clickIndex in 1...count {
            try ensureCanActuate()
            try postMouseEvent(type: downType, point: point, button: cgButton, clickState: Int64(clickIndex))
            try? await Task.sleep(nanoseconds: 25_000_000)
            try postMouseEvent(type: upType, point: point, button: cgButton, clickState: Int64(clickIndex))
            if clickIndex < count {
                try? await Task.sleep(nanoseconds: 45_000_000)
            }
        }
        lastPoint = point
    }

    public func mouseDown(at point: CGPoint, button: ClickyMouseButton = .left) async throws {
        try await moveMouse(to: point, smoothSteps: 6)
        try ensureCanActuate()

        let (downType, cgButton): (CGEventType, CGMouseButton) = {
            switch button {
            case .left: return (.leftMouseDown, .left)
            case .right: return (.rightMouseDown, .right)
            case .center: return (.otherMouseDown, .center)
            }
        }()
        try postMouseEvent(type: downType, point: point, button: cgButton, clickState: 1)
        lastPoint = point
    }

    public func mouseUp(at point: CGPoint, button: ClickyMouseButton = .left) async throws {
        try ensureCanActuate()

        let (upType, cgButton): (CGEventType, CGMouseButton) = {
            switch button {
            case .left: return (.leftMouseUp, .left)
            case .right: return (.rightMouseUp, .right)
            case .center: return (.otherMouseUp, .center)
            }
        }()
        try postMouseEvent(type: upType, point: point, button: cgButton, clickState: 1)
        lastPoint = point
    }

    public func drag(from startPoint: CGPoint, to endPoint: CGPoint, steps: Int = 18) async throws {
        try await moveMouse(to: startPoint, smoothSteps: 8)
        try ensureCanActuate()

        try postMouseEvent(type: .leftMouseDown, point: startPoint, button: .left, clickState: 1)
        try? await Task.sleep(nanoseconds: 40_000_000)

        let totalSteps = max(2, steps)
        for stepIndex in 1...totalSteps {
            try ensureCanActuate()
            let progress = CGFloat(stepIndex) / CGFloat(totalSteps)
            let intermediate = CGPoint(
                x: startPoint.x + (endPoint.x - startPoint.x) * progress,
                y: startPoint.y + (endPoint.y - startPoint.y) * progress
            )
            try postMouseEvent(type: .leftMouseDragged, point: intermediate, button: .left, clickState: 1)
            lastPoint = intermediate
            try? await Task.sleep(nanoseconds: 14_000_000)
        }

        try postMouseEvent(type: .leftMouseUp, point: endPoint, button: .left, clickState: 1)
        lastPoint = endPoint
    }

    public func scroll(at point: CGPoint? = nil, deltaY: Int32, deltaX: Int32 = 0) async throws {
        if let point {
            try await moveMouse(to: point, smoothSteps: 4)
        }
        try ensureCanActuate()

        guard let scrollEvent = CGEvent(
            scrollWheelEvent2Source: eventSource,
            units: .pixel,
            wheelCount: 2,
            wheel1: deltaY,
            wheel2: deltaX,
            wheel3: 0
        ) else {
            throw ClickyAppDriverError.eventCreationFailed("scroll")
        }

        tagAndPost(scrollEvent)
    }

    // MARK: - Keyboard Actuation

    public func typeText(_ text: String) async throws {
        try ensureCanActuate()

        for scalar in text.unicodeScalars {
            try ensureCanActuate()

            if scalar == "\n" || scalar == "\r" {
                try await pressKey("return")
                continue
            }
            if scalar == "\t" {
                try await pressKey("tab")
                continue
            }

            var utf16Units = Array(String(scalar).utf16)
            guard let keyDown = CGEvent(keyboardEventSource: eventSource, virtualKey: 0, keyDown: true),
                  let keyUp = CGEvent(keyboardEventSource: eventSource, virtualKey: 0, keyDown: false) else {
                throw ClickyAppDriverError.eventCreationFailed("unicode key")
            }

            keyDown.keyboardSetUnicodeString(stringLength: utf16Units.count, unicodeString: &utf16Units)
            keyUp.keyboardSetUnicodeString(stringLength: utf16Units.count, unicodeString: &utf16Units)

            tagAndPost(keyDown)
            tagAndPost(keyUp)
            try? await Task.sleep(nanoseconds: 8_000_000)
        }
    }

    public func pressKey(_ keyName: String, modifiers: CGEventFlags = []) async throws {
        try ensureCanActuate()

        guard let keyCode = virtualKeyCode(for: keyName) else {
            throw ClickyAppDriverError.unsupportedKey(keyName)
        }

        guard let keyDown = CGEvent(keyboardEventSource: eventSource, virtualKey: keyCode, keyDown: true),
              let keyUp = CGEvent(keyboardEventSource: eventSource, virtualKey: keyCode, keyDown: false) else {
            throw ClickyAppDriverError.eventCreationFailed(keyName)
        }

        if !modifiers.isEmpty {
            keyDown.flags = modifiers
            keyUp.flags = modifiers
        }

        tagAndPost(keyDown)
        try? await Task.sleep(nanoseconds: 20_000_000)
        tagAndPost(keyUp)
    }

    /// Parses and presses a chord such as `"cmd+shift+s"` or `"command+c"`.
    public func pressKeyCombo(_ combo: String) async throws {
        let parts = combo
            .split(separator: "+")
            .map { $0.trimmingCharacters(in: .whitespacesAndNewlines).lowercased() }
            .filter { !$0.isEmpty }

        guard let primaryKey = parts.last else {
            throw ClickyAppDriverError.unsupportedKey(combo)
        }

        var flags: CGEventFlags = []
        for modifier in parts.dropLast() {
            switch modifier {
            case "cmd", "command", "super":
                flags.insert(.maskCommand)
            case "shift":
                flags.insert(.maskShift)
            case "opt", "option", "alt":
                flags.insert(.maskAlternate)
            case "ctrl", "control":
                flags.insert(.maskControl)
            case "fn":
                flags.insert(.maskSecondaryFn)
            default:
                throw ClickyAppDriverError.unsupportedKey(modifier)
            }
        }

        try await pressKey(primaryKey, modifiers: flags)
    }

    // MARK: - Accessibility (AXUIElement) Helpers

    public func isAccessibilityTrusted() -> Bool {
        AXIsProcessTrusted()
    }

    public func frontmostApplication() -> NSRunningApplication? {
        NSWorkspace.shared.frontmostApplication
    }

    public func frontmostApplicationElement() -> AXUIElement? {
        guard let pid = NSWorkspace.shared.frontmostApplication?.processIdentifier else {
            return nil
        }
        return AXUIElementCreateApplication(pid)
    }

    public func focusedWindow(of applicationElement: AXUIElement? = nil) -> AXUIElement? {
        guard let appElement = applicationElement ?? frontmostApplicationElement() else {
            return nil
        }
        return copyAXElementAttribute(appElement, attribute: kAXFocusedWindowAttribute as String)
    }

    public func focusedUIElement() -> AXUIElement? {
        let systemWide = AXUIElementCreateSystemWide()
        return copyAXElementAttribute(systemWide, attribute: kAXFocusedUIElementAttribute as String)
    }

    public func elementAtScreenPoint(_ cgPoint: CGPoint) -> AXUIElement? {
        let systemWide = AXUIElementCreateSystemWide()
        var element: AXUIElement?
        let status = AXUIElementCopyElementAtPosition(systemWide, Float(cgPoint.x), Float(cgPoint.y), &element)
        return status == .success ? element : nil
    }

    public func elementRole(_ element: AXUIElement) -> String? {
        copyAXStringAttribute(element, attribute: kAXRoleAttribute as String)
    }

    public func elementTitle(_ element: AXUIElement) -> String? {
        copyAXStringAttribute(element, attribute: kAXTitleAttribute as String)
            ?? copyAXStringAttribute(element, attribute: kAXDescriptionAttribute as String)
    }

    public func elementValue(_ element: AXUIElement) -> String? {
        copyAXStringAttribute(element, attribute: kAXValueAttribute as String)
    }

    public func elementFrame(_ element: AXUIElement) -> CGRect? {
        var positionValue: CFTypeRef?
        var sizeValue: CFTypeRef?

        guard AXUIElementCopyAttributeValue(element, kAXPositionAttribute as CFString, &positionValue) == .success,
              AXUIElementCopyAttributeValue(element, kAXSizeAttribute as CFString, &sizeValue) == .success,
              let posRef = positionValue,
              let sizeRef = sizeValue,
              CFGetTypeID(posRef) == AXValueGetTypeID(),
              CFGetTypeID(sizeRef) == AXValueGetTypeID() else {
            return nil
        }

        var origin = CGPoint.zero
        var size = CGSize.zero
        guard AXValueGetValue(posRef as! AXValue, .cgPoint, &origin),
              AXValueGetValue(sizeRef as! AXValue, .cgSize, &size) else {
            return nil
        }

        return CGRect(origin: origin, size: size)
    }

    @discardableResult
    public func pressElement(_ element: AXUIElement) -> Bool {
        AXUIElementPerformAction(element, kAXPressAction as CFString) == .success
    }

    public func findElement(
        in root: AXUIElement,
        role: String? = nil,
        titleContains substring: String? = nil,
        maxDepth: Int = 6
    ) -> AXUIElement? {
        guard maxDepth >= 0 else { return nil }

        let currentRole = elementRole(root)
        let currentTitle = elementTitle(root)

        let roleMatches = (role == nil) || (currentRole == role)
        let titleMatches: Bool = {
            guard let substring, !substring.isEmpty else { return true }
            return currentTitle?.localizedCaseInsensitiveContains(substring) == true
        }()

        if roleMatches && titleMatches && (role != nil || substring != nil) {
            return root
        }

        guard maxDepth > 0 else { return nil }
        for child in childElements(of: root) {
            if let match = findElement(in: child, role: role, titleContains: substring, maxDepth: maxDepth - 1) {
                return match
            }
        }
        return nil
    }

    public func triggerMenuStep(_ step: ClickyMenuStep) async throws -> Bool {
        try ensureCanActuate()
        switch step {
        case .title(let title):
            guard let appElement = frontmostApplicationElement(),
                  let menuBar: AXUIElement = copyAXElementAttribute(appElement, attribute: kAXMenuBarAttribute as String),
                  let item = findElement(in: menuBar, role: kAXMenuItemRole as String, titleContains: title, maxDepth: 6) else {
                return false
            }
            return pressElement(item)
        case .shortcut(let key, let modifiers):
            try await pressKey(key, modifiers: modifiers)
            return true
        }
    }

    // MARK: - Private Helpers

    private func ensureCanActuate() throws {
        if userTookOver || shouldAbortCheck() {
            userTookOver = true
            throw ClickyAppDriverError.userTookOver
        }
    }

    private func postMouseEvent(
        type: CGEventType,
        point: CGPoint,
        button: CGMouseButton,
        clickState: Int64
    ) throws {
        guard let event = CGEvent(
            mouseEventSource: eventSource,
            mouseType: type,
            mouseCursorPosition: point,
            mouseButton: button
        ) else {
            throw ClickyAppDriverError.eventCreationFailed("mouse event")
        }
        event.setIntegerValueField(.mouseEventClickState, value: clickState)
        tagAndPost(event)
    }

    private func tagAndPost(_ event: CGEvent) {
        event.setIntegerValueField(.eventSourceUserData, value: Self.syntheticEventUserDataTag)
        event.post(tap: .cghidEventTap)
    }

    private func copyAXElementAttribute(_ element: AXUIElement, attribute: String) -> AXUIElement? {
        var value: CFTypeRef?
        guard AXUIElementCopyAttributeValue(element, attribute as CFString, &value) == .success,
              let value,
              CFGetTypeID(value) == AXUIElementGetTypeID() else {
            return nil
        }
        return (value as! AXUIElement)
    }

    private func copyAXStringAttribute(_ element: AXUIElement, attribute: String) -> String? {
        var value: CFTypeRef?
        guard AXUIElementCopyAttributeValue(element, attribute as CFString, &value) == .success else {
            return nil
        }
        return value as? String
    }

    private func childElements(of element: AXUIElement) -> [AXUIElement] {
        var value: CFTypeRef?
        guard AXUIElementCopyAttributeValue(element, kAXChildrenAttribute as CFString, &value) == .success,
              let array = value as? [AXUIElement] else {
            return []
        }
        return array
    }

    private func virtualKeyCode(for rawName: String) -> CGKeyCode? {
        let name = rawName.trimmingCharacters(in: .whitespacesAndNewlines).lowercased()
        let keyMap: [String: CGKeyCode] = [
            "a": 0, "s": 1, "d": 2, "f": 3, "h": 4, "g": 5, "z": 6, "x": 7, "c": 8, "v": 9,
            "b": 11, "q": 12, "w": 13, "e": 14, "r": 15, "y": 16, "t": 17,
            "1": 18, "2": 19, "3": 20, "4": 21, "6": 22, "5": 23, "=": 24, "9": 25, "7": 26,
            "-": 27, "8": 28, "0": 29, "]": 30, "o": 31, "u": 32, "[": 33, "i": 34, "p": 35,
            "return": 36, "enter": 36, "l": 37, "j": 38, "'": 39, "k": 40, ";": 41, "\\": 42,
            ",": 43, "/": 44, "n": 45, "m": 46, ".": 47, "tab": 48,
            "space": 49, "spacebar": 49, "`": 50,
            "backspace": 51, "delete": 51, "del": 51,
            "escape": 53, "esc": 53,
            "f1": 122, "f2": 120, "f3": 99, "f4": 118, "f5": 96, "f6": 97,
            "f7": 98, "f8": 100, "f9": 101, "f10": 109, "f11": 103, "f12": 111,
            "home": 115, "pageup": 116, "forwarddelete": 117, "end": 119, "pagedown": 121,
            "arrowleft": 123, "left": 123,
            "arrowright": 124, "right": 124,
            "arrowdown": 125, "down": 125,
            "arrowup": 126, "up": 126
        ]
        return keyMap[name]
    }
}
